// ── API pública ─────────────────────────────────────────────────
function t(key, params) {
  const dict = I18N[_lang] || I18N.pt;
  let s = dict[key] ?? I18N.pt[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

const Lang = {
  current: () => _lang,
  set(code) {
    if (I18N[code]) {
      _lang = code;
      try { localStorage.setItem("vitula_lang", code); } catch(e){}
      Lang.apply();
      try { window.dispatchEvent(new Event("vitula-lang")); } catch (e) {}   // controles de toque etc. se atualizam
    }
  },
  list: () => ({ ...LANGS }),
  init() {
    try { const s = localStorage.getItem("vitula_lang"); if (s && I18N[s]) _lang = s; } catch(e){}
  },

  // Reescreve os campos de texto dos objetos de dados no idioma atual.
  // Chamado após data.js e equip.js carregarem (via Lang.applyOnBoot)
  // e sempre que o idioma muda (via Lang.set).
  apply() {
    if (typeof VOCATIONS === "undefined") return; // dados ainda não carregaram

    // ── Vocações ──
    for (const id in VOCATIONS) {
      const V = VOCATIONS[id];
      V.name = t("voc_" + id);
      V.desc = t("voc_" + id + "_desc");
      V.trait = t("voc_" + id + "_trait");
      if (V.passive) {
        V.passive.name = t("voc_" + id + "_passive_name");
        V.passive.desc = t("voc_" + id + "_passive_desc");
      }
    }

    // ── Promoção ──
    if (typeof PROMOTION !== "undefined") {
      for (const id in PROMOTION) PROMOTION[id].name = t("promo_" + id);
    }

    // ── Regiões ──
    for (const id in REGIONS) {
      REGIONS[id].name = t("region_" + id);
      REGIONS[id].desc = t("region_" + id + "_desc");
    }

    // ── Monstros ──
    for (const id in MONSTERS) {
      MONSTERS[id].name = t("mon_" + id);
      const pKey = "mon_" + id + "_p";
      if (I18N[_lang][pKey] || I18N.pt[pKey]) MONSTERS[id].plural = t(pKey);
    }

    // ── Itens ──
    const ITEM_KEY_MAP = {
      gold: "item_gold_coin", silver: "item_silver_coin", apple: "item_apple",
      bread: "item_bread", meat: "item_meat", health_potion: "item_health_potion",
      blue_gem: "item_blue_gem", red_gem: "item_red_gem", bronze_key: "item_bronze_key",
      scroll: "item_scroll",
    };
    if (typeof ITEMS !== "undefined") {
      for (const id in ITEM_KEY_MAP) if (ITEMS[id]) ITEMS[id].name = t(ITEM_KEY_MAP[id]);
      // itens de equipamento (criados em equip.js: ITEMS["eq_" + id])
      if (typeof EQUIP !== "undefined") {
        for (const eid in EQUIP) {
          const iid = "eq_" + eid;
          if (ITEMS[iid]) ITEMS[iid].name = t("eq_" + eid) || EQUIP[eid].name;
        }
        if (ITEMS.boss_essence) ITEMS.boss_essence.name = t("item_boss_essence");
      }
    }

    // ── Elementos ──
    if (typeof ELEMENTS !== "undefined") {
      const EL_MAP = { physical: "el_physical", fire: "el_fire", ice: "el_ice", earth: "el_earth", energy: "el_energy", holy: "el_holy" };
      for (const id in EL_MAP) if (ELEMENTS[id]) ELEMENTS[id].name = t(EL_MAP[id]);
    }

    // ── Equipamentos ──
    if (typeof EQUIP !== "undefined") {
      for (const id in EQUIP) {
        const key = "eq_" + id;
        EQUIP[id].name = t(key);
        const dKey = key + "_desc";
        if (I18N[_lang][dKey] || I18N.pt[dKey]) EQUIP[id].desc = t(dKey);
      }
    }

    // ── Raridades ──
    if (typeof RARITY !== "undefined") {
      for (let i = 0; i < RARITY.length; i++) RARITY[i].name = t("rarity_" + i);
    }

    // ── Skills ──
    if (typeof SKILLS !== "undefined") {
      for (const id in SKILLS) {
        SKILLS[id].name = t("skill_" + id);
        SKILLS[id].desc = t("skill_" + id + "_desc");
      }
    }

    // ── Atributos ──
    if (typeof ATTRS !== "undefined") {
      const ATTR_SHOW = {
        str:   n => t("attr_str_show", { n: n * 2 }),
        vit:   n => t("attr_vit_show", { n: n * 25 }),
        crit:  n => t("attr_crit_show", { n: (10 + n * 0.5).toFixed(1).replace(".", ",") }),
        block: n => t("attr_block_show", { n: (n * 0.5).toFixed(1).replace(".", ",") }),
        armor: n => t("attr_defense_show", { n: (n * 0.5).toFixed(1).replace(".", ",") }),
        weapon: n => `+${n}`,
        ml:     n => `+${n}`,
        shield: n => `+${n}`,
        aspd:  n => t("attr_aspd_show", { n: (n * 0.25).toFixed(2).replace(".", ",") }),
        hpreg: n => t("attr_hpreg_show", { n: (n * 0.5).toFixed(1).replace(".", ",") }),
        mpreg: n => t("attr_mpreg_show", { n: (n * 0.5).toFixed(1).replace(".", ",") }),
      };
      for (const id in ATTRS) {
        const key = id === "shield" ? "attr_shield_attr" : "attr_" + id;
        ATTRS[id].name = t(key);
        ATTRS[id].desc = t("attr_" + id + "_desc");
        if (ATTR_SHOW[id]) ATTRS[id].show = ATTR_SHOW[id];
      }
    }

    // ── Feitiços do Cavaleiro ──
    if (typeof SPELLS !== "undefined") {
      const SP_MAP = { front: "spell_front", heal: "spell_heal", spin: "spell_spin", aura: "spell_aura" };
      for (const id in SP_MAP) {
        if (SPELLS[id]) { SPELLS[id].name = t(SP_MAP[id]); SPELLS[id].desc = t(SP_MAP[id] + "_desc"); }
      }
    }

    // ── Feitiços do Arqueiro ──
    if (typeof ARCHER_SPELLS !== "undefined") {
      const ASP_MAP = { holy: "spell_holy_arrow", heal: "spell_heal", rain: "spell_arrow_rain", eagle: "spell_eagle_eye" };
      for (const id in ASP_MAP) {
        if (ARCHER_SPELLS[id]) { ARCHER_SPELLS[id].name = t(ASP_MAP[id]); ARCHER_SPELLS[id].desc = t(ASP_MAP[id] + "_desc"); }
      }
    }

    // ── Poções ──
    if (typeof POTIONS !== "undefined") {
      for (const id in POTIONS) {
        POTIONS[id].name = t("pot_" + id);
        POTIONS[id].desc = t("pot_" + id + "_desc");
      }
    }

    // ── Loja de atributos ──
    if (typeof SHOP !== "undefined") {
      const SHOP_DESC = {
        hp:     n => t("shop_hp_desc", { n: n * 10 }),
        atkspd: n => t("shop_atkspd_desc", { n: n * 5 }),
        armor:  n => t("shop_armor_desc", { n }),
        fury:   n => t("shop_fury_desc", { n: n * 10 }),
      };
      for (const id in SHOP) {
        SHOP[id].name = t("shop_" + id);
        if (SHOP_DESC[id]) SHOP[id].desc = SHOP_DESC[id];
      }
    }

    // ── Bênçãos ──
    if (typeof BLESS_TEXT !== "undefined") {
      for (let i = 0; i < BLESS_TEXT.length; i++) BLESS_TEXT[i] = t("bless_" + (i + 1));
    }

    // ── Contratos de caça ──
    if (typeof CONTRACT_TIERS !== "undefined") {
      const TIER_KEYS = ["contract_easy", "contract_medium", "contract_hard"];
      for (let i = 0; i < CONTRACT_TIERS.length; i++) CONTRACT_TIERS[i].name = t(TIER_KEYS[i]);
    }
  },
};
Lang.init();
